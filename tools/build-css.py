#!/usr/bin/env python3
"""Join and minify the stylesheets into dist/marinara-desktop.min.css.

Marinara accepts at most 256 KiB of extension CSS (manifest cssPath, joined).
The readable sources stay as they are; manifest.json loads only the minified
file this script writes. Run it after editing any of SOURCES:

    python3 tools/build-css.py          # rebuild
    python3 tools/build-css.py --check  # fail if dist is stale or too big

Minifying only drops comments and collapses whitespace (around { } ; and
after a property's colon); strings are kept as they are.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ["desktop.css", "theme.css", "layout.css", "home.css", "win11.css"]
OUT = ROOT / "dist" / "marinara-desktop.min.css"
CAP = 256 * 1024
HEADER = "/* Generated by tools/build-css.py from " + ", ".join(SOURCES) + ". Do not edit. */\n"


def minify(css: str) -> str:
    # One pass that knows comments and strings: comments go, strings are kept
    # verbatim, everything else has its whitespace collapsed.
    pieces, buf, i, n = [], [], 0, len(css)

    def flush():
        if buf:
            pieces.append(("code", "".join(buf)))
            buf.clear()

    while i < n:
        c = css[i]
        if c == "/" and css.startswith("/*", i):
            end = css.find("*/", i + 2)
            i = n if end < 0 else end + 2
            buf.append(" ")
            continue
        if c in "\"'":
            j = i + 1
            while j < n and css[j] != c:
                j += 2 if css[j] == "\\" else 1
            flush()
            pieces.append(("str", css[i : j + 1]))
            i = j + 1
            continue
        buf.append(c)
        i += 1
    flush()
    out = []
    for kind, text in pieces:
        if kind == "code":
            text = re.sub(r"\s+", " ", text)
        out.append((kind, text))
    joined = "".join(t if k == "code" else "\0%d\0" % idx for idx, (k, t) in enumerate(out))
    joined = re.sub(r" ?([{};]) ?", r"\1", joined)
    joined = joined.replace(";}", "}")
    joined = re.sub(r"([{;]-?-?[A-Za-z][-\w]*): ", r"\1:", joined)
    return re.sub(r"\0(\d+)\0", lambda m: out[int(m.group(1))][1], joined).strip() + "\n"


def build() -> str:
    parts = [minify((ROOT / name).read_text(encoding="utf-8")) for name in SOURCES]
    return HEADER + "".join(parts)


def main() -> int:
    css = build()
    size = len(css.encode("utf-8"))
    if size > CAP:
        print(f"too big: {size} bytes > {CAP}", file=sys.stderr)
        return 1
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != css:
            print("dist/marinara-desktop.min.css is stale: run python3 tools/build-css.py", file=sys.stderr)
            return 1
        print(f"ok: {size} bytes ({CAP - size} left)")
        return 0
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(css, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {size} bytes ({CAP - size} left)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
